    name = "Not-A-Robot Check"
    intro = "Security gate ahead. Just prove you're human. Easy."
    GATE = [(18, r) for r in range(4, 15)]
    LABELS = ["FLAG", "FLAG", "FLAG", "FLAG", "SPIKE", "SPIKE", "TORGRIM", "MIKKEL", "CLOUD"]
    MAX_CHECKS = 3

    def setup(self):
        self.passed = False
        self.attempts = 0
        self.checks = 0
        self.pp = None
        self.wait = 0.0
        self.labels = []
        self.selected = set()
        self.cells = []
        self.grid_f = None

    def build(self):
        self.floor()
        if not self.passed:
            for c, r in self.GATE:
                self.grid[r][c] = "="
        self.grid[14][23] = "^"
        self.flag = Flag(self.g, [(27, 14, "stay")])

    def update(self, dt, p):
        if not self.popup_done and p.cx > 8 * T:
            self.popup_done = True
            self.open_check()
        if self.wait > 0:
            self.wait -= dt
            if self.wait <= 0:
                self.open_check()

    def open_check(self):
        if self.g.closing or self.g.level is not self or self.passed:
            return
        self.checks += 1
        self.pp = self.g.spawn_popup(title="Not-A-Robot Check", body="Select ALL the flags, then press VERIFY.",
                                     button=False, size=(400, 260), content=self._build, on_close=self._closed)
        self.g.say("A security check. Select all the flags. Take your time. (Not too much time.)")

    def _build(self, frame, pp):
        self.grid_f = tk.Frame(frame, bg="#161a2e")
        self.grid_f.pack(pady=(6, 4))
        tk.Button(frame, text="VERIFY", command=self._verify, bg=C_YELLOW, fg="#1a1a1a", relief="flat",
                  padx=16, font=self.g.font_small).pack()
        self._shuffle()

    def _shuffle(self):
        for w in self.grid_f.winfo_children():
            w.destroy()
        self.labels = random.sample(self.LABELS, len(self.LABELS))
        self.selected = set()
        self.cells = []
        for i, lab in enumerate(self.labels):
            b = tk.Button(self.grid_f, text=lab, width=9, relief="flat", bg="#2a2f52", fg="#eef0ff",
                          activebackground="#3b4270", font=self.g.font_small,
                          command=lambda i=i: self._toggle(i))
            b.grid(row=i // 3, column=i % 3, padx=2, pady=2)
            self.cells.append(b)

    def _toggle(self, i):
        if i in self.selected:
            self.selected.discard(i)
        else:
            self.selected.add(i)
        self.cells[i].configure(bg="#2f8a4a" if i in self.selected else "#2a2f52")
        self.g.sfx.play("click")

    def _verify(self):
        flags = {i for i, lab in enumerate(self.labels) if lab == "FLAG"}
        if self.selected != flags:
            self.g.sfx.play("bad")
            self.g.say(random.choice(["Beep boop. That's EXACTLY what a robot would pick.",
                                      "Suspicious. Very suspicious. Try again, human.",
                                      "Torgrim is not a flag. Mikkel is not a flag. Try again."]))
            self._shuffle()
        elif self.attempts == 0:
            self.attempts += 1
            self.g.sfx.play("bad")
            self.g.say("Hmm. Correct, but too FAST. Humans are slower than that. Again, please.")
            self._shuffle()
        else:
            self.g.sfx.play("ok")
            self.g.say("Verified: probably human. The gate is open.")
            self.g.add_score(50)
            self.pp.on_close = None
            self.pp.close()
            self.open_gate()

    def _closed(self):
        if self.passed or self.g.level is not self:
            return
        self.g.sfx.play("toss")
        if self.checks < self.MAX_CHECKS:
            self.g.say("Closing the check doesn't make you human. Here's another one.")
            self.wait = 1.5
        else:
            self.g.say("FINE. You're human. Probably. Go.")
            self.open_gate()

    def open_gate(self):
        if self.passed:
            return
        self.passed = True
        self.smash(self.GATE)


