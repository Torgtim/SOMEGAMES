class Planks:
    """Temporary planks you create by clicking. Max two at once; the oldest retires."""
    LIFE, MAX, WIDTH = 2.6, 2, 90

    def __init__(self, level):
        self.lvl = level
        self.items = []                     # [x, y, time_left]

    def place(self, mx, my):
        g = self.lvl.g
        x, y = mx - self.WIDTH / 2, my - 6
        p = g.p
        if p.x < x + self.WIDTH and p.x + PW > x and p.y < y + 12 and p.y + PH > y:
            y = p.y + PH if g.gdir > 0 else p.y - 12      # clicked on yourself: put it under your feet
        if len(self.items) >= self.MAX:
            self.items.pop(0)
        self.items.append([x, y, self.LIFE])
        g.sfx.play("plank")

    def update(self, dt):
        for it in self.items:
            it[2] -= dt
        if any(it[2] <= 0 for it in self.items):
            self.lvl.g.sfx.play("plank_gone")
        self.items = [it for it in self.items if it[2] > 0]

    def rects(self):
        return [(x, y, x + self.WIDTH, y + 12, None) for x, y, _ in self.items]

    def draw(self, cv):
        for x, y, left in self.items:
            blink = left < 0.7 and int(left * 10) % 2 == 0
            cv.create_rectangle(x, y, x + self.WIDTH, y + 12, fill="#c8914e" if not blink else "#f0d9b0",
                                outline="#6b4420", width=2, tags="dyn")
            cv.create_text(x + self.WIDTH / 2, y + 6, text=f"{left:.1f}s", fill="#3b2410",
                           font=("Segoe UI", 7, "bold"), tags="dyn")


