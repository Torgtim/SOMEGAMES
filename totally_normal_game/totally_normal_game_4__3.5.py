RATE = 22050


def _note(semi):
    """Frequency of a note, in semitones relative to A4 (440 Hz)."""
    return 440.0 * 2 ** (semi / 12)


def _synth(parts):
    """parts: list of (freq, dur, vol, wave, slide). freq 0 = silence.
    Returns a list of floats in -1..1."""
    out = []
    for freq, dur, vol, wv, slide in parts:
        n = int(RATE * dur)
        phase = 0.0
        attack = RATE * 0.004
        for i in range(n):
            k = i / n
            if freq <= 0:
                out.append(0.0)
                continue
            phase += freq * (slide ** k) / RATE
            ph = phase % 1.0
            if wv == "sq":
                v = 1.0 if ph < 0.5 else -1.0
            elif wv == "tri":
                v = 4 * ph - 1 if ph < 0.5 else 3 - 4 * ph
            elif wv == "sin":
                v = math.sin(phase * math.tau)
            else:
                v = random.uniform(-1, 1)
            env = min(1.0, i / attack) * (1 - k) ** 1.4
            out.append(v * vol * env)
    return out


def _music():
    """A short, slightly jazzy chiptune loop (8 bars): bass + lead + hi-hat."""
    beat = 60 / 132
    step = beat / 2                         # eighth notes
    # chord roots per bar (semitones from A4): Dm7 G7 Cmaj Am  Dm7 G7 Em A7
    roots = [-7, -14, -9, -12, -7, -14, -5, -12]
    pats = [
        [12, 15, None, 19, 22, None, 19, 15],
        [10, None, 14, 17, None, 14, 10, None],
        [12, 16, 19, 23, None, 19, 16, None],
        [12, None, 15, 19, 15, None, 24, None],
        [12, 15, 19, None, 22, 19, 15, 12],
        [10, 14, 17, 20, None, 17, 14, None],
        [12, None, 15, 19, None, 15, 12, None],
        [11, 14, None, 19, 23, None, 24, None],
    ]
    n_step = int(RATE * step)
    buf = [0.0] * (n_step * 8 * len(roots))
    pos = 0
    for bar, root in enumerate(roots):
        for s in range(8):
            bass_note = root - 12 + (7 if s in (2, 6) else 0) + (12 if s % 2 else 0)
            for i, v in enumerate(_synth([(_note(bass_note), step, 0.15, "tri", 1.0)])):
                buf[pos + i] += v
            off = pats[bar][s]
            if off is not None:
                for i, v in enumerate(_synth([(_note(root + off), step * 0.85, 0.065, "sq", 1.0)])):
                    buf[pos + i] += v
            for i, v in enumerate(_synth([(1, 0.025, 0.045 if s % 2 else 0.03, "noise", 1.0)])):
                buf[pos + i] += v
            pos += n_step
    return buf


