class L3(Level):
    name = "Loading..."
    intro = "The bridge is still loading. Please wait. (It only loads while you stand still.)"
    X0, X1, Y = 9 * T, 25 * T, 15 * T
    STALL = 0.9                         # the bar "gets stuck at 99%" (really 90%)

    def setup(self):
        self.prog = 0.0
        self.last_tick = 0

    def build(self):
        self.floor(0, 8)
        self.floor(25, 31)
        self.fill(9, 17, 24, 17, "^")
        self.flag = Flag(self.g, [(28, 14, "stay")])

    def shown(self):
        return int(self.prog / self.STALL * 99)

    def update(self, dt, p):
        still = p.on and abs(p.vx) < 15
        if self.prog < self.STALL:
            if still:
                self.prog = min(self.STALL, self.prog + 0.13 * dt)
                if self.shown() // 10 > self.last_tick:
                    self.last_tick = self.shown() // 10
                    self.g.sfx.play("load")
                if self.prog >= self.STALL:
                    self.g.sfx.play("loaded")
                    self.g.say("Stuck at 99%. Classic. That last bit you'll have to jump.")
            elif self.prog > 0.02:
                self.once("moving", "Loading pauses while you move. Nobody knows why. It's tradition.")

    def extras(self):
        w = (self.X1 - self.X0) * self.prog
        return [(self.X0, self.Y, self.X0 + w, self.Y + 30, None)] if w > 1 else []

    def draw_dyn(self, cv):
        x0, x1, y = self.X0, self.X1, self.Y
        cv.create_rectangle(x0, y, x1, y + 30, fill="", outline="#c8d0ff", width=2, dash=(4, 3), tags="dyn")
        w = (x1 - x0) * self.prog
        if w > 1:
            cv.create_rectangle(x0, y, x0 + w, y + 30, fill="#3fc76a", outline="#1e7a3c", width=2, tags="dyn")
            for sx in range(int(x0), int(x0 + w) - 10, 24):
                cv.create_line(sx, y + 30, sx + 12, y, fill="#6fe894", width=4, tags="dyn")
        cv.create_text((x0 + x1) / 2, y - 16, text=f"LOADING BRIDGE...  {self.shown()}%",
                       fill=C_WHITE, font=self.g.font_ui, tags="dyn")


class L4(Level):
    name = "Volume Up"
    intro = "Drag the volume slider up! (Mouse wheel and + / - work too.)"
    TX, TOP, BOT, KW = 450, 5 * T, 15 * T, 96

    def setup(self):
        self.target = self.BOT
        self.ky = float(self.BOT)

    def build(self):
        self.floor()
        self.fill(17, 5, 31, 5, "=")
        self.flag = Flag(self.g, [(28, 4, "stay")])
        self.target = self.BOT
        self.ky = float(self.BOT)

    def aim(self, y):
        self.target = max(self.TOP, min(self.BOT, y))

    def on_click(self, x, y):
        if self.TX - 90 < x < self.TX + 90:
            self.aim(y)

    def on_drag(self, x, y):
        self.on_click(x, y)

    def on_wheel(self, d):
        self.aim(self.target - d * 30)

    def on_key(self, k):
        if k in ("plus", "equal", "kp_add"):
            self.aim(self.target - 40)
            return True
        if k in ("minus", "kp_subtract"):
            self.aim(self.target + 40)
            return True
        return False

    def level(self):
        return (self.BOT - self.ky) / (self.BOT - self.TOP)

    def update(self, dt, p):
        step = 200 * dt                       # max knob speed, so it carries you smoothly
        if abs(self.target - self.ky) <= step:
            self.ky = self.target
        else:
            self.ky += step if self.target > self.ky else -step
        self.g.sfx.set_music_volume(0.25 + 0.75 * self.level())
        if self.level() > 0.5:
            self.once("loud", "LOUDER! (it's also an elevator, in case that wasn't clear)")

    def extras(self):
        x0 = self.TX - self.KW / 2
        return [(x0, self.ky, x0 + self.KW, self.ky + 16, None)]

    def draw_dyn(self, cv):
        tx = self.TX
        cv.create_rectangle(tx - 4, self.TOP - 20, tx + 4, self.BOT, fill="#2a2f52", outline="", tags="dyn")
        cv.create_text(tx, self.TOP - 34, text="VOLUME", fill=C_WHITE, font=self.g.font_small, tags="dyn")
        x0 = tx - self.KW / 2
        cv.create_rectangle(x0, self.ky, x0 + self.KW, self.ky + 16, fill="#e8ecff", outline="#5b7bd6",
                            width=2, tags="dyn")
        cv.create_text(tx, self.ky + 8, text=f"{int(self.level() * 100)}%", fill=C_INK,
                       font=("Segoe UI", 8, "bold"), tags="dyn")


class L5(Level):
    name = "Past Self"
    intro = "Press Z to undo! You go back to the start... but your past self keeps doing what you did."
    PLATE = (7 * T, 9 * T)                      # x-range of the pressure plate
    DOOR = [(20, r) for r in range(8, 15)]

    def setup(self):
        self.rec = []
        self.ghost = None
        self.gi = 0
        self.open = False

    def build(self):
        self.floor()
        for c, r in self.DOOR:
            self.grid[r][c] = "D"
        self.flag = Flag(self.g, [(27, 14, "stay")])
        self.open = False

    def on_plate(self, x, y):
        return abs(y + PH - 15 * T) < 3 and x + PW > self.PLATE[0] and x < self.PLATE[1]

    def on_key(self, k):
        if k != "z":
            return False
        if len(self.rec) < 20:
            self.g.say("Nothing to undo yet. Do something first.")
            return True
        self.ghost, self.gi, self.rec = self.rec, 0, []
        self.g.sfx.play("rewind")
        self.g.respawn()
        self.once("ghost", "Meet your past self. It will do EXACTLY what you did. No pressure.")
        return True

    def update(self, dt, p):
        self.rec.append((p.x, p.y, p.face))
        if len(self.rec) > 60 * 30:
            self.rec.pop(0)
        if self.ghost:
            self.gi = min(self.gi + 1, len(self.ghost) - 1)
        pressed = self.on_plate(p.x, p.y)
        if self.ghost:
            gx, gy, _ = self.ghost[self.gi]
            pressed = pressed or self.on_plate(gx, gy)
        in_door = p.x + PW > 20 * T and p.x < 21 * T        # never close the door ON the player
        want = pressed or (self.open and in_door)
        if want != self.open:
            self.open = want
            for c, r in self.DOOR:
                self.grid[r][c] = "d" if want else "D"
            self.g.static_dirty = True
            self.g.sfx.play("door")
        if pressed:
            self.once("plate", "Plate pressed, door open. Now... how do you get there while standing here?")

    def on_death(self):
        self.rec = []
        return {1: "Stand on the plate, then press Z. Trust your past self."}.get(self.deaths)

    def draw_dyn(self, cv):
        x0, x1 = self.PLATE
        cv.create_rectangle(x0, 15 * T - 6, x1, 15 * T, fill="#3fc76a" if self.open else C_RED,
                            outline=C_INK, tags="dyn")
        if self.ghost:
            gx, gy, face = self.ghost[self.gi]
            cv.create_oval(gx, gy, gx + PW, gy + PH, fill="#9fd8ff", outline="#3a6ea5", width=2,
                           stipple="gray50", tags="dyn")
            cv.create_text(gx + PW / 2, gy - 8, text="past you", fill="#dff1ff",
                           font=("Segoe UI", 7, "bold"), tags="dyn")


class L6(Level):
    name = "Special Delivery"
    intro = "The flag ordered a parcel. The parcel is a popup. You're the courier."
    CAGE = (23, 9, 27, 14)                # c0, r0, c1, r1 of the cage around the flag
    MAX_PARCELS = 3

    def setup(self):
        self.delivered = False
        self.parcel = None
        self.parcels = 0
        self.wait = 0.0

    def build(self):
        self.floor()
        self.grid[14][11] = "^"
        self.grid[14][17] = "^"
        self.flag = Flag(self.g, [(25, 14, "stay")])
        if not self.delivered:
            c0, r0, c1, r1 = self.CAGE
            self.fill(c0, r0, c1, r0, "=")
            self.fill(c0, r0, c0, r1, "=")
            self.fill(c1, r0, c1, r1, "=")

    def flag_screen_pos(self):
        cv = self.g.canvas
        return cv.winfo_rootx() + self.flag.x, cv.winfo_rooty() + self.flag.y - 50

    def send_parcel(self):
        if self.g.closing or self.g.level is not self or self.delivered:
            return
        self.parcels += 1
        cv = self.g.canvas
        self.parcel = self.g.spawn_popup(
            title="Parcel for: THE FLAG",
            body="[ PARCEL ]  Drag me onto the flag! Grab me anywhere. "
                 "(Handle with care. Contents: one (1) level exit.)",
            pos=(cv.winfo_rootx() + 40, cv.winfo_rooty() + 60),
            button=False, draggable=True, on_close=self._tossed)
        self.g.say("Drag the parcel window across your screen and drop it on the flag. Yes, the real window.")

    def _tossed(self):
        """Player closed the parcel with the window's X instead of delivering it."""
        if self.delivered or self.g.level is not self:
            return
        self.parcel = None
        self.g.sfx.play("toss")
        if self.parcels < self.MAX_PARCELS:
            self.g.say("You threw the parcel away?! Luckily I ordered a spare.")
            self.wait = 1.5
        else:
            self.g.say("Fine. I'll deliver it MYSELF. Unbelievable.")
            self.open_cage()

    def update(self, dt, p):
        if not self.popup_done and self.t > 1.0:
            self.popup_done = True
            self.send_parcel()
        if self.wait > 0:
            self.wait -= dt
            if self.wait <= 0:
                self.send_parcel()
        pp = self.parcel
        if pp and pp.alive and not self.delivered:
            try:
                px, py = pp.screen_center()
                fx, fy = self.flag_screen_pos()
            except tk.TclError:
                return
            d = math.hypot(px - fx, py - fy)
            if d < 70:
                pp.on_close = None
                pp.close()
                self.parcel = None
                self.g.add_score(50)
                self.g.sfx.play("deliver")
                self.g.say("Parcel delivered! The flag is thrilled. The cage is open.")
                self.open_cage()
            elif d < 220:
                self.g.caption("[ warmer... ]" if d > 140 else "[ HOT! almost there ]")

    def open_cage(self):
        if self.delivered:
            return
        self.delivered = True
        c0, r0, c1, r1 = self.CAGE
        self.smash([(c, r) for r in range(r0, r1 + 1) for c in range(c0, c1 + 1)
                    if self.grid[r][c] == "="])

    def on_death(self):
        return {1: "The courier died. The parcel is fine, don't worry."}.get(self.deaths)


