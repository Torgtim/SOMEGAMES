class Sound:
    """Generates every sound as a .wav in a temp folder, then plays them with
    the best backend available. Never required: if anything fails, the game
    simply runs silently."""

    def __init__(self):
        self.enabled = True
        self.backend = None
        self.files = {}
        self.snd = {}
        self.procs = []
        self.last = {}
        self.music_ch = None
        self.dir = tempfile.mkdtemp(prefix="tng35_sound_")
        try:
            for name, parts in SFX_RECIPES.items():
                self.files[name] = self._write(name, _synth(parts))
        except Exception:
            self.files = {}
            return
        self._pick_backend()

    def _write(self, name, samples):
        data = array.array("h", (int(max(-1.0, min(1.0, s)) * 32767) for s in samples))
        if sys.byteorder == "big":
            data.byteswap()
        path = os.path.join(self.dir, name + ".wav")
        with wave.open(path, "wb") as wf:
            wf.setnchannels(1)
            wf.setsampwidth(2)
            wf.setframerate(RATE)
            wf.writeframes(data.tobytes())
        return path

    def _pick_backend(self):
        # 1) pygame-ce mixer: real mixing, so music + effects at the same time
        try:
            os.environ.setdefault("PYGAME_HIDE_SUPPORT_PROMPT", "1")
            import pygame
            pygame.mixer.init(frequency=RATE, size=-16, channels=1, buffer=512)
            pygame.mixer.set_num_channels(16)
            self.pg = pygame
            self.snd = {n: pygame.mixer.Sound(p) for n, p in self.files.items()}
            music = pygame.mixer.Sound(self._write("music", _music()))
            music.set_volume(0.55)
            self.music_ch = pygame.mixer.Channel(15)
            pygame.mixer.set_reserved(1)
            self.music_ch.play(music, loops=-1)
            self.backend = "pygame"
            return
        except Exception:
            self.snd = {}
        # 2) Windows built-in (one sound at a time, no music)
        if sys.platform.startswith("win"):
            try:
                import winsound
                self.ws = winsound
                self.backend = "winsound"
                return
            except Exception:
                pass
        # 3) command-line players
        for cmd in (["afplay"], ["paplay"], ["aplay", "-q"]):
            if shutil.which(cmd[0]):
                self.cmd = cmd
                self.backend = "cmd"
                return

    @property
    def label(self):
        if not self.backend:
            return "Sound: unavailable"
        return f"Sound: {'ON' if self.enabled else 'OFF'} (M)"

    def play(self, name):
        if not (self.enabled and self.backend and name in self.files):
            return
        now = time.monotonic()
        if now - self.last.get(name, 0) < 0.05:     # don't machine-gun the same sound
            return
        self.last[name] = now
        try:
            if self.backend == "pygame":
                self.snd[name].play()
            elif self.backend == "winsound":
                self.ws.PlaySound(self.files[name], self.ws.SND_FILENAME | self.ws.SND_ASYNC
                                  | self.ws.SND_NODEFAULT)
            else:
                self.procs = [p for p in self.procs if p.poll() is None]
                if len(self.procs) < 6:
                    self.procs.append(subprocess.Popen(self.cmd + [self.files[name]],
                                                       stdout=subprocess.DEVNULL,
                                                       stderr=subprocess.DEVNULL))
        except Exception:
            pass

    def set_music_volume(self, v):
        """0..1 -- only does anything with the pygame backend (the only one with music)."""
        if self.backend == "pygame" and self.music_ch:
            try:
                self.music_ch.set_volume(max(0.0, min(1.0, v)))
            except Exception:
                pass

    def toggle(self):
        self.enabled = not self.enabled
        try:
            if self.backend == "pygame" and self.music_ch:
                if self.enabled:
                    self.music_ch.unpause()
                else:
                    self.music_ch.pause()
            elif self.backend == "winsound" and not self.enabled:
                self.ws.PlaySound(None, 0)
        except Exception:
            pass

    def shutdown(self):
        try:
            if self.backend == "pygame":
                self.pg.mixer.quit()
            elif self.backend == "winsound":
                self.ws.PlaySound(None, 0)
            for p in self.procs:
                p.poll()
        except Exception:
            pass
        shutil.rmtree(self.dir, ignore_errors=True)


