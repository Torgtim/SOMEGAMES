        cv.create_text(W / 2, 260, text=f"Deaths: {d}", fill=C_WHITE, font=("Segoe UI", 20, "bold"), tags="dyn")
        cv.create_text(W / 2, 300, text=f"Score: {self.score}", fill=C_WHITE, font=("Segoe UI", 20, "bold"), tags="dyn")
        cv.create_text(W / 2, 340, text=f"Popups closed: {self.popups_closed}", fill=C_WHITE,
                       font=("Segoe UI", 20, "bold"), tags="dyn")
        cv.create_text(W / 2, 385, text=f"Rank: {rank}", fill="#ff9e9e", font=("Segoe UI", 22, "bold"), tags="dyn")
        cv.create_text(W / 2, H - 30, text="Close this window (or click QUIT) to exit", fill="#8a8ea8",
                       font=self.font_small, tags="dyn")

