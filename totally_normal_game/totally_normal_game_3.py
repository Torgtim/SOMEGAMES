# ------------------------------------------------------------- sound
RATE = 22050


def _note(semi):
    """Frequency of a note, in semitones relative to A4 (440 Hz)."""
    return 440.0 * 2 ** (semi / 12)


def _synth(parts):
    """parts: list of (freq, dur, vol, wave, slide). freq 0 = silence.
    Returns a list of floats in -1..1."""
    out = []
    for freq, dur, vol, wv, slide in parts:
        n = int(RATE * dur)
        phase = 0.0
        attack = RATE * 0.004
        for i in range(n):
            k = i / n
            if freq <= 0:
                out.append(0.0)
                continue
            phase += freq * (slide ** k) / RATE
            ph = phase % 1.0
            if wv == "sq":
                v = 1.0 if ph < 0.5 else -1.0
            elif wv == "tri":
                v = 4 * ph - 1 if ph < 0.5 else 3 - 4 * ph
            elif wv == "sin":
                v = math.sin(phase * math.tau)
            else:
                v = random.uniform(-1, 1)
            env = min(1.0, i / attack) * (1 - k) ** 1.4
            out.append(v * vol * env)
    return out


def _music():
    """A short bouncy chiptune loop (8 bars) built from a bass line and a lead."""
    beat = 60 / 150
    step = beat / 2                         # eighth notes
    # chord roots per bar (semitones from A4): C  G  Am  F  C  G  F  G
    roots = [-9, -14, -12, -16, -9, -14, -16, -14]
    # lead pattern per bar: offsets over the chord root, None = rest
    pats = [
        [12, None, 16, 19, 16, None, 12, None],
        [11, None, 14, 19, 14, None, 11, 14],
        [12, None, 15, 19, 24, 19, 15, None],
        [12, 16, 19, None, 21, 19, 16, None],
        [12, None, 16, 19, 16, None, 24, None],
        [11, None, 14, 19, 23, 19, 14, None],
        [12, 16, 19, 24, 19, 16, 12, None],
        [11, None, 14, None, 19, None, 23, 24],
    ]
    n_step = int(RATE * step)
    total = n_step * 8 * len(roots)
    buf = [0.0] * total
    pos = 0
    for bar, root in enumerate(roots):
        for s in range(8):
            bass = _synth([(_note(root - 12 + (12 if s % 2 else 0)), step, 0.16, "tri", 1.0)])
            for i, v in enumerate(bass):
                buf[pos + i] += v
            off = pats[bar][s]
            if off is not None:
                lead = _synth([(_note(root + off), step * 0.9, 0.07, "sq", 1.0)])
                for i, v in enumerate(lead):
                    buf[pos + i] += v
            if s % 2 == 0:
                hat = _synth([(1, 0.03, 0.05, "noise", 1.0)])
                for i, v in enumerate(hat):
                    buf[pos + i] += v
            pos += n_step
    return buf


