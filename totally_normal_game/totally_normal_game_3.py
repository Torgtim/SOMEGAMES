class Player:
    def __init__(self, x, y):
        self.x, self.y = float(x), float(y)
        self.vx = self.vy = 0.0
        self.on = False
        self.coyote = 0.0
        self.buffer = 0.0
        self.face = 1
        self.dead = False

    def rect(self):
        return (self.x, self.y, self.x + PW, self.y + PH)

    @property
    def cx(self):
        return self.x + PW / 2


class Flag:
    def __init__(self, game, spots, msgs=()):
        self.g = game
        self.spots = spots
        self.msgs = list(msgs)
        self.i = 0
        c, r, _ = spots[0]
        self.x, self.y = c * T + T / 2, (r + 1) * T
        self.anim = None
        self.wait = 0.0

    def trigger(self):
        return self.spots[self.i][2]

    def update(self, dt, p):
        if self.anim:
            a = self.anim
            a["t"] += dt
            k = min(1.0, a["t"] / a["d"])
            self.x = a["x0"] + (a["x1"] - a["x0"]) * k
            self.y = a["y0"] + (a["y1"] - a["y0"]) * k - math.sin(k * math.pi) * a["h"]
            if k >= 1:
                self.anim = None
                self.wait = 0.0
            return
        self.wait += dt
        trig = self.trigger()
        go = False
        if trig == "near":
            go = abs(p.cx - self.x) < 120 and abs(p.y + PH - self.y) < 110
        elif isinstance(trig, (int, float)):
            go = self.wait >= trig
        if go and self.i + 1 < len(self.spots):
            self.hop()

    def hop(self):
        if self.i < len(self.msgs) and self.msgs[self.i]:
            self.g.say(self.msgs[self.i])
        self.i += 1
        c, r, _ = self.spots[self.i]
        x1, y1 = c * T + T / 2, (r + 1) * T
        dist = math.hypot(x1 - self.x, y1 - self.y)
        self.anim = {"t": 0.0, "d": 0.5 + dist / 1400, "x0": self.x, "y0": self.y,
                     "x1": x1, "y1": y1, "h": 80 + dist * 0.15}
        self.g.sfx.play("hop")

    def touching(self, p):
        return self.anim is None and (self.x - 4 < p.rect()[2] and self.x + 26 > p.rect()[0]
                                       and self.y - 96 < p.rect()[3] and self.y > p.rect()[1])


