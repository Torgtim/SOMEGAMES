class Level:
    name = "?"
    intro = ""
    wrap = False            # leaving one side of the screen puts you on the other
    tomb_mode = False       # dying leaves a solid tombstone where you died
    free_deaths = False     # deaths here don't count towards the total
    narrator_rect = None    # (x0, y0, x1, y1): narrator box drawn here and SOLID

    def __init__(self, game):
        self.g = game
        self.phase = 0
        self.deaths = 0
        self.said = set()
        self.start = (2, 14)
        # Everything set here survives respawns. build() runs again on every
        # respawn, so anything that must happen only ONCE per level visit
        # (popups, opened walls, tombstones, typed letters) lives here instead.
        self.popup_done = False
        self.wall_gone = False
        self.tombs = []
        self.setup()
        self.reset()

    def setup(self):
        pass

    def reset(self):
        self.grid = [["." for _ in range(COLS)] for _ in range(ROWS)]
        self.popped = {}
        self.crumble = {}
        self.revealed = set()
        self.flag = None
        self.t = 0.0
        self.build()
        for c, r in self.tombs:
            self.grid[r][c] = "T"

    def fill(self, c0, r0, c1, r1, ch):
        for r in range(r0, r1 + 1):
            for c in range(c0, c1 + 1):
                if 0 <= r < ROWS and 0 <= c < COLS:
                    self.grid[r][c] = ch

    def floor(self, c0=0, c1=COLS - 1):
        self.fill(c0, 15, c1, 17, "#")

    def once(self, key, text):
        if key not in self.said:
            self.said.add(key)
            self.g.say(text)

    def spawn(self):
        c, r = self.start
        return c * T + (T - PW) / 2, (r + 1) * T - PH

    def build(self):
        pass

    def extras(self):
        """Extra solid rectangles (x0, y0, x1, y1, None) that aren't grid tiles."""
        if self.narrator_rect:
            return [tuple(self.narrator_rect) + (None,)]
        return []

    def update(self, dt, p):
        pass

    def hazard(self, p):
        return False

    def on_flag(self):
        return True

    def on_death(self):
        return None

    def on_type(self, k):
        """Called for letter keys. Return True if the level used the key."""
        return False

    def letter_at(self, c, r):
        return "?"

    def draw_dyn(self, cv):
        pass


