class GamePopup:
    """A real little Toplevel window that is unmistakably part of the game."""

    def __init__(self, game, title=None, body=None, runaway=False, on_close=None):
        self.game = game
        self.runaway = runaway
        self.on_close = on_close
        t, b = random.choice(POPUP_LINES)
        title, body = title or t, body or b
        self.win = tk.Toplevel(game.root)
        self.win.title(f"{TITLE} - {title}")
        self.win.configure(bg="#161a2e")
        self.win.resizable(False, False)
        self.win.attributes("-topmost", True)
        w, h = 300, 130
        sw, sh = game.root.winfo_screenwidth(), game.root.winfo_screenheight()
        x = random.randint(40, max(41, sw - w - 40))
        y = random.randint(40, max(41, sh - h - 40))
        self.win.geometry(f"{w}x{h}+{x}+{y}")
        self.win.protocol("WM_DELETE_WINDOW", self.close)
        # keys typed while a popup has focus still reach the game
        self.win.bind("<KeyPress>", game.on_key_down)
        self.win.bind("<KeyRelease>", game.on_key_up)

        bar = tk.Frame(self.win, bg="#2a2f52", height=26)
        bar.pack(fill="x")
        tk.Label(bar, text=title, bg="#2a2f52", fg="#eef0ff", font=game.font_small,
                 anchor="w").pack(side="left", padx=8)
        body_f = tk.Frame(self.win, bg="#161a2e")
        body_f.pack(fill="both", expand=True, padx=10, pady=8)
        tk.Label(body_f, text=body, bg="#161a2e", fg="#eef0ff", wraplength=270,
                 justify="left", font=game.font_small).pack(anchor="w")
        btns = tk.Frame(body_f, bg="#161a2e")
        btns.pack(side="bottom", fill="x", pady=(10, 0))
        tk.Button(btns, text="OK", command=self.close, bg=C_YELLOW, fg="#1a1a1a",
                  activebackground="#fff08a", relief="flat", padx=14,
                  font=game.font_small).pack(side="right")

        self.alive = True
        if self.runaway:
            self._flee_tick()

    def close(self):
        if not self.alive:
            return
        self.alive = False
        try:
            self.win.destroy()
        except tk.TclError:
            pass
        self.game.on_popup_closed(self)
        if self.on_close:
            self.on_close()

    def dismiss(self):
        """Quietly remove a leftover popup (no bonus, not counted as closed)."""
        if not self.alive:
            return
        self.alive = False
        try:
            self.win.destroy()
        except tk.TclError:
            pass

    def _flee_tick(self):
        if not self.alive:
            return
        try:
            mx, my = self.win.winfo_pointerxy()
            wx, wy = self.win.winfo_x(), self.win.winfo_y()
            ww, wh = self.win.winfo_width(), self.win.winfo_height()
            cx, cy = wx + ww / 2, wy + wh / 2
            if math.hypot(mx - cx, my - cy) < 160:
                ang = math.atan2(cy - my, cx - mx)
                sw, sh = self.game.root.winfo_screenwidth(), self.game.root.winfo_screenheight()
                nx = max(10, min(sw - ww - 10, int(cx + math.cos(ang) * 190 - ww / 2)))
                ny = max(10, min(sh - wh - 10, int(cy + math.sin(ang) * 190 - wh / 2)))
                self.win.geometry(f"+{nx}+{ny}")
        except tk.TclError:
            return
        self.win.after(60, self._flee_tick)


