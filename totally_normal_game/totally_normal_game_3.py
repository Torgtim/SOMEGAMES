class L4(Level):
    name = "Hear The Path"
    intro = "Turn your sound ON. The path is invisible, but it isn't quiet."

    def setup(self):
        self.beep_t = 0.0

    def build(self):
        self.floor()
        self.fill(7, 14, 25, 14, "^")
        self.fill(9, 12, 11, 12, "I")
        self.fill(15, 11, 17, 11, "I")
        self.fill(21, 12, 23, 12, "I")
        self.flag = Flag(self.g, [(29, 14, "stay")])

    def update(self, dt, p):
        if not self.g.sfx.enabled or not self.g.sfx.backend:
            self.once("muted", "Sound's off, so I'll caption the beeps for you. How kind of me.")
        best = None
        for r in range(ROWS):
            for c in range(COLS):
                if self.grid[r][c] == "I" and (c, r) not in self.revealed:
                    d = math.hypot(p.cx - (c * T + T / 2), p.y + PH / 2 - (r * T + T / 2))
                    best = d if best is None else min(best, d)
        self.beep_t -= dt
        if best is not None and best < 240 and self.beep_t <= 0:
            self.beep_t = 0.12 + 0.55 * (best / 240)
            if best < 90:
                self.g.sfx.play("beep3")
                self.g.caption("[ BEEP! BEEP! BEEP! ]")
            elif best < 160:
                self.g.sfx.play("beep2")
                self.g.caption("[ beep BEEP ]")
            else:
                self.g.sfx.play("beep1")
                self.g.caption("[ faint beep ]")

